/**
 * Нерабочие и сокращённые дни по производственному календарю РФ.
 * 2026: постановление Правительства РФ от 24.09.2025 № 1466.
 * 2027: календарь, утверждённый осенью 2026 (перенос выходных: 2 января на 5 ноября, 3 января на 31 декабря, 20 февраля на 22 февраля).
 * Сокращённые предпраздничные дни 2027 года здесь не заполнены: их список нужно сверить с официальным текстом.
 * Даты можно менять вручную в админке.
 */
export interface HolidaySeed { date: string; kind: 'closed' | 'short'; note: string }

const range = (from: string, to: string, note: string): HolidaySeed[] => {
  const out: HolidaySeed[] = [];
  for (let t = Date.parse(from + 'T00:00:00Z'); t <= Date.parse(to + 'T00:00:00Z'); t += 86400000) {
    out.push({ date: new Date(t).toISOString().slice(0, 10), kind: 'closed', note });
  }
  return out;
};

